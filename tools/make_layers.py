#!/usr/bin/env python3
"""Epsilon 808: install the hybrid layer sounds into the project.

    python3 tools/make_layers.py <folder with *.flac + manifest.json>
    python3 tools/make_layers.py --fonts-only      (BinaryData without any sounds: what the public repository holds)

- copies each sound to Resources/Layers/Layer_<name>.flac
- writes Source/LayerLibrary.h (name, file, group, root note, measured fundamental)
- regenerates JuceLibraryCode/BinaryData.h/.cpp in Projucer's format (fonts + layers)
- lists the files in Epsilon-808.jucer (as resources) and CMakeLists.txt (binary data)
"""
import json, os, re, shutil, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fonts_only = sys.argv[1] == '--fonts-only'
src = None if fonts_only else sys.argv[1]
manifest = [] if fonts_only else json.load(open(os.path.join(src, 'manifest.json')))
layer_dir = os.path.join(root, 'Resources', 'Layers')
os.makedirs(layer_dir, exist_ok=True)
if not fonts_only:
    for f in os.listdir(layer_dir):
        os.remove(os.path.join(layer_dir, f))

entries = []
for m in manifest:
    fn = 'Layer_' + m['file']
    shutil.copyfile(os.path.join(src, m['file']), os.path.join(layer_dir, fn))
    entries.append(dict(m, resource=fn))

# ---------------------------------------------------------------- Source/LayerLibrary.h
lines = None if fonts_only else ['#pragma once', '',
         '// The hybrid layer sounds built into Epsilon 808. Generated by tools/make_layers.py: do not edit by hand.',
         '// rootHz is each sound\'s measured fundamental; the engine tunes playback to it, so every layer lands in tune.',
         '', 'struct LayerInfo { const char* name; const char* file; const char* group; int rootNote; float rootHz; };', '',
         'inline constexpr LayerInfo layerInfos[] = {']
for e in entries if not fonts_only else []:
    lines.append(f'    {{ "{e["name"]}", "{e["resource"]}", "{e["group"]}", {e["root"]}, {e["f0"]:.3f}f }},')
if not fonts_only: lines += ['};', 'inline constexpr int layerInfoCount = static_cast<int>(sizeof(layerInfos) / sizeof(layerInfos[0]));', '']
if not fonts_only:
    open(os.path.join(root, 'Source', 'LayerLibrary.h'), 'w').write('\n'.join(lines))

# ---------------------------------------------------------------- BinaryData (Projucer format)
fonts = ['BarlowSemiCondensed-Medium.ttf', 'BarlowSemiCondensed-SemiBold.ttf', 'BarlowSemiCondensed-Bold.ttf']
files = [(f, os.path.join(root, 'Resources', f)) for f in fonts] + [(e['resource'], os.path.join(layer_dir, e['resource'])) for e in entries]

def ident(name):
    s = re.sub(r'[^A-Za-z0-9_]', '', name.replace('.', '_'))
    return '_' + s if s[0].isdigit() else s

def jhash(s):  # Projucer's resource-name hash (same as JUCE's String::hashCode on UTF-8 chars)
    h = 0
    for ch in s:
        h = (31 * h + ord(ch)) & 0xffffffff
    return h

h = ['/* =========================================================================================', '',
     '   This is an auto-generated file: Any edits you make may be overwritten!', '', '*/', '', '#pragma once', '', 'namespace BinaryData', '{']
cpp = ['/* ==================================== JUCER_BINARY_RESOURCE ====================================', '',
       '   This is an auto-generated file: Any edits you make may be overwritten!', '', '*/', '', '#include <cstring>', '',
       'namespace BinaryData', '{', '']
for i, (name, path) in enumerate(files):
    data = open(path, 'rb').read()
    var = ident(name)
    h += [f'    extern const char*   {var};', f'    const int            {var}Size = {len(data)};', '']
    cpp.append(f'//================== {name} ==================')
    cpp.append(f'static const unsigned char temp_binary_data_{i}[] =')
    body = ','.join(str(b) for b in data)
    chunks = [body[j:j + 4000] for j in range(0, len(body), 4000)]
    cpp.append('{ ' + '\n'.join(chunks) + ',0,0};')
    cpp.append('')
    cpp.append(f'const char* {var} = (const char*) temp_binary_data_{i};')
    cpp.append('')
h += ['    // Number of elements in the namedResourceList and originalFileNames arrays.',
      f'    const int namedResourceListSize = {len(files)};', '',
      '    // Points to the start of a list of resource names.', '    extern const char* namedResourceList[];', '',
      '    // Points to the start of a list of resource filenames.', '    extern const char* originalFilenames[];', '',
      '    // If you provide the name of one of the binary resource variables above, this function will',
      '    // return the corresponding data and its size (or a null pointer if the name isn\'t found).',
      '    const char* getNamedResource (const char* resourceNameUTF8, int& dataSizeInBytes);', '',
      '    // If you provide the name of one of the binary resource variables above, this function will',
      '    // return the corresponding original, non-mangled filename (or a null pointer if the name isn\'t found).',
      '    const char* getNamedResourceOriginalFilename (const char* resourceNameUTF8);', '}', '']
cpp += ['', 'const char* getNamedResource (const char* resourceNameUTF8, int& numBytes);',
        'const char* getNamedResource (const char* resourceNameUTF8, int& numBytes)', '{',
        '    unsigned int hash = 0;', '', '    if (resourceNameUTF8 != nullptr)',
        '        while (*resourceNameUTF8 != 0)', '            hash = 31 * hash + (unsigned int) *resourceNameUTF8++;', '',
        '    switch (hash)', '    {']
for name, path in files:
    var = ident(name)
    cpp.append(f'        case 0x{jhash(var):08x}:  numBytes = {len(open(path, "rb").read())}; return {var};')
cpp += ['        default: break;', '    }', '', '    numBytes = 0;', '    return nullptr;', '}', '',
        'const char* namedResourceList[] =', '{'] + [f'    "{ident(n)}",' for n, _ in files] + ['};', '',
        'const char* originalFilenames[] =', '{'] + [f'    "{n}",' for n, _ in files] + ['};', '',
        'const char* getNamedResourceOriginalFilename (const char* resourceNameUTF8);',
        'const char* getNamedResourceOriginalFilename (const char* resourceNameUTF8)', '{',
        '    for (unsigned int i = 0; i < (sizeof (namedResourceList) / sizeof (namedResourceList[0])); ++i)',
        '        if (strcmp (namedResourceList[i], resourceNameUTF8) == 0)', '            return originalFilenames[i];', '',
        '    return nullptr;', '}', '', '}', '']
open(os.path.join(root, 'JuceLibraryCode', 'BinaryData.h'), 'w').write('\n'.join(h))
open(os.path.join(root, 'JuceLibraryCode', 'BinaryData.cpp'), 'w').write('\n'.join(cpp))

if fonts_only:
    print('BinaryData written with fonts only'); sys.exit(0)

# ---------------------------------------------------------------- .jucer
jp = os.path.join(root, 'Epsilon-808.jucer'); j = open(jp).read()
j = re.sub(r'\s*<GROUP id="B8grLy" name="Layers">.*?</GROUP>', '', j, flags=re.S)
grp = ['      <GROUP id="B8grLy" name="Layers">']
for k, e in enumerate(entries):
    grp.append(f'        <FILE id="B8Ly{k:02d}" name="{e["resource"]}" compile="0" resource="1" file="Resources/Layers/{e["resource"]}"/>')
grp.append('      </GROUP>')
j = j.replace('      <FILE id="B8Fn04" name="Barlow-OFL.txt" compile="0" resource="0" file="Resources/Barlow-OFL.txt"/>\n',
              '      <FILE id="B8Fn04" name="Barlow-OFL.txt" compile="0" resource="0" file="Resources/Barlow-OFL.txt"/>\n' + '\n'.join(grp) + '\n')
if 'LayerLibrary.h' not in j:
    j = j.replace('      <FILE id="B8Pr02" name="PluginProcessor.h" compile="0" resource="0" file="Source/PluginProcessor.h"/>\n',
                  '      <FILE id="B8Pr02" name="PluginProcessor.h" compile="0" resource="0" file="Source/PluginProcessor.h"/>\n'
                  '      <FILE id="B8LyLb" name="LayerLibrary.h" compile="0" resource="0" file="Source/LayerLibrary.h"/>\n')
open(jp, 'w').write(j)

# ---------------------------------------------------------------- CMakeLists.txt
cp = os.path.join(root, 'CMakeLists.txt'); c = open(cp).read()
# CMakeLists.txt picks up whatever is in Resources/Layers (a glob), so nothing to edit there
print(len(entries), 'layers installed;', sum(os.path.getsize(p) for _, p in files) // 1024, 'KB of binary data')
